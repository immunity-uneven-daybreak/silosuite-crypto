/// Custom global allocator for the WASM build that zeroizes freed
/// memory before returning it to the allocator's free list. Closes
/// a residual-secrets-in-WASM-linear-memory class of finding. See
/// the module docs for the full rationale.
#[cfg(target_arch = "wasm32")]
mod zeroizing_alloc;

pub use errors::{CryptoError, CryptoResult};

/// AEAD envelope version constants.
///
/// All ciphertext blobs produced by this crate are prefixed with two
/// big-endian bytes that identify the algorithm and version. New versions
/// are added when primitives are rotated; old versions remain decryptable.
pub mod envelope_versions {
    /// XChaCha20-Poly1305 with 24-byte nonce.
    pub const V1_XCHACHA20_POLY1305: u16 = 0x0001;
}

/// Length constants used throughout the crate.
pub mod lengths {
    /// Symmetric key length (XChaCha20-Poly1305).
    pub const SYMMETRIC_KEY_LEN: usize = 32;
    /// XChaCha20-Poly1305 nonce length.
    pub const XCHACHA_NONCE_LEN: usize = 24;
    /// Poly1305 tag length.
    pub const POLY1305_TAG_LEN: usize = 16;
    /// Argon2id salt length.
    pub const ARGON2_SALT_LEN: usize = 16;
    /// Master key length.
    pub const MASTER_KEY_LEN: usize = 32;
    /// X25519 key length (public or private).
    pub const X25519_KEY_LEN: usize = 32;
    /// Ed25519 public/secret key length.
    pub const ED25519_KEY_LEN: usize = 32;
}
