//! # silosuite-crypto
//!
//! Cryptographic primitives for `SiloSuite`, sharing one implementation
//! between native server-side use and browser-side use (via WASM).
//!
//! ## Design philosophy
//!
//! - **Established primitives only.** Every algorithm comes from the
//!   `RustCrypto` or dalek-cryptography projects, with BIP-39 recovery
//!   phrases from the rust-bitcoin `bip39` crate.
//! - **No userspace crypto.** This crate composes those primitives; it
//!   does not implement them.
//! - **Constant-time by default.** All comparisons of secret values use
//!   `subtle::ConstantTimeEq`. All AEAD comparisons are handled by the
//!   underlying primitive crates which are constant-time by design.
//! - **Memory zeroization.** Secret keys (`MasterKey`, derived KEKs,
//!   private keys) implement `Zeroize` and `ZeroizeOnDrop` so that
//!   ephemeral key material is wiped from memory after use.
//! - **Versioned envelopes.** Every ciphertext is prefixed with a 2-byte
//!   algorithm version so we can rotate primitives without breaking
//!   stored data.
//!
//! ## Modules
//!
//! - [`aead`]: XChaCha20-Poly1305 envelope format
//! - [`kdf`]: Argon2id key derivation with capability detection
//! - [`hkdf`]: HKDF-SHA256 (RFC 5869) with test vectors
//! - [`master_key`]: the master-key flow (signup/unlock/rewrap/recover)
//! - [`asymmetric`]: X25519 sealed boxes + Ed25519 signatures
//! - [`recovery`]: BIP-39 phrase generation and KEK derivation
//! - [`dek`]: per-resource data encryption key (DEK) helpers
//! - [`constant_time`]: constant-time comparison helpers
//!
//! ## WASM exports
//!
//! When compiled for `wasm32-unknown-unknown`, the [`wasm_bindings`]
//! module exposes JavaScript-callable wrappers around the public API.
//! TypeScript type definitions are generated by `wasm-bindgen` at build
//! time.

